out = ['/* generated by tools/gen_font.py: printable ASCII 32..126 at scales k = 1..4, 8k x 16k cells, 8-bit coverage, row-major.', ' *']
out += [' * ' + l for l in NOTICE.split('\n')] + [' */', '#pragma once']
for k in range(1, 5):
    font = ImageFont.truetype(TTF, 13 * k)
    asc, desc = font.getmetrics()
    w, h = 8 * k, 16 * k
    out.append(f'static const unsigned char font_ui{k}[95][{w * h}] = {{')
    for c in range(32, 127):
        im = Image.new('L', (w, h), 0)
        ImageDraw.Draw(im).text((0, h - asc - desc + k), chr(c), fill=255, font=font)
        out.append('    { ' + ','.join(str(b) for b in im.tobytes()) + ' },' + (f' /* {chr(c)} */' if chr(c) not in '*/\\' else ''))
    out.append('};')
out.append('static const unsigned char *font_ui_glyph(int k, int c) {   /* k = 1..4, c = 32..126 */')
out.append('    return k >= 4 ? font_ui4[c - 32] : k == 3 ? font_ui3[c - 32] : k == 2 ? font_ui2[c - 32] : font_ui1[c - 32];')
out.append('}')
print('\n'.join(out))
